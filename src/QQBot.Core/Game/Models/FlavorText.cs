    /// <summary>
    /// 确定性抽句：同一种子材料必得同一句（可复现、可审计）。
    /// </summary>
    public static string Pick(string key, string seedMaterial)
    {
        if (!Pools.TryGetValue(key, out var pool) || pool.Length == 0)
            return "";
        var rng = new Random(DeterministicSeed($"flavor|{key}|{seedMaterial}"));
        return pool[rng.Next(pool.Length)];
    }

    /// <summary>
    /// 在结果消息后按概率附加风味句。
    /// 仅用于结果类文案；冷却/错误等功能性提示一律不装饰。
    /// </summary>
    public static string Decorate(string baseMsg, string key, string seedMaterial, double probability = 0.7)
    {
        var rng = new Random(DeterministicSeed($"flavor|{key}|{seedMaterial}"));
        if (rng.NextDouble() >= probability) return baseMsg;
        if (!Pools.TryGetValue(key, out var pool) || pool.Length == 0) return baseMsg;
        return $"{baseMsg}\n{pool[rng.Next(pool.Length)]}";
    }

    /// <summary>启动自检：所有文案池非空（防内容配置错误静默上线）。</summary>
    public static void Validate()
    {
        foreach (var (key, pool) in Pools)
        {
            if (pool.Length == 0)
                throw new InvalidOperationException($"FlavorText pool '{key}' is empty.");
        }
    }

    private static int DeterministicSeed(string key)
    {
        var hash = 5381;
        foreach (var c in key)
            hash = ((hash << 5) + hash) ^ c;
        return hash & 0x7FFFFFFF;
    }
